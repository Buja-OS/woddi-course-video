-- v186e: every certificate carries the cohort it was awarded in.
-- Cohort = the learner's admission cycle at the time the certificate was issued (admissions.cycle_name).
-- Learners with no admission record get the academic cycle running (or most recently started) on the issue date.
-- The cohort is fixed when the certificate is issued; learners cannot change it afterwards.

alter table public.certificates add column if not exists cohort text;

create or replace function public.cohort_for(p_uid text, p_at timestamptz)
returns text language sql stable security definer set search_path = public as $$
  select coalesce(
    (select a.cycle_name from admissions a
      where a.uid::text = p_uid and a.admitted_at <= coalesce(p_at, now())
      order by a.admitted_at desc limit 1),
    (select a.cycle_name from admissions a where a.uid::text = p_uid order by a.admitted_at limit 1),
    (select c.name from academic_cycles c
      where make_date(c.year, c.start_month, 1) <= (coalesce(p_at, now()) at time zone 'Africa/Lagos')::date
      order by make_date(c.year, c.start_month, 1) desc limit 1),
    'Pioneer cohort');
$$;
revoke all on function public.cohort_for(text, timestamptz) from public, anon, authenticated;
grant execute on function public.cohort_for(text, timestamptz) to service_role;

-- set on issue (fires before certificates_dedupe / guard / set_code: triggers run in name order)
create or replace function public.certificates_cohort()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  -- only an admin may set a cohort by hand; everyone else gets the computed one
  if new.cohort is null or coalesce(public.get_my_role(), '') <> 'admin' then
    new.cohort := public.cohort_for(new.uid, coalesce(new.issued_at, now()));
  end if;
  return new;
end $$;
drop trigger if exists certificates_cohort on public.certificates;
create trigger certificates_cohort before insert on public.certificates
  for each row execute function public.certificates_cohort();

-- learners cannot edit it later (same guard as the other printed fields)
create or replace function public.certificates_guard()
returns trigger language plpgsql as $$
begin
  if current_user not in ('authenticated', 'anon') or coalesce(public.get_my_role(), '') = 'admin' then
    return new;
  end if;
  if tg_op = 'INSERT' then
    new.credential_code := null;          -- always generated by certificates_set_code
    new.revoked := false; new.revoked_at := null; new.revoke_reason := null;
    new.replaced_by := null; new.corrected_at := null;
    if new.issued_at is null or new.issued_at > now() then new.issued_at := now(); end if;
    return new;
  end if;
  new.uid := old.uid;
  new.credential_code := old.credential_code;
  new.revoked := old.revoked; new.revoked_at := old.revoked_at; new.revoke_reason := old.revoke_reason;
  new.replaced_by := old.replaced_by; new.corrected_at := old.corrected_at;
  new.issued_at := old.issued_at;
  new.course_name := old.course_name; new.title := old.title; new.course_id := old.course_id;
  new.student_name := old.student_name;
  new.cohort := old.cohort;
  return new;
end $$;

-- existing certificates
update public.certificates set cohort = public.cohort_for(uid, issued_at) where cohort is null;

-- the public check returns the cohort too
create or replace function public.verify_credential(p_code text default null, p_course text default null, p_uid text default null)
returns jsonb language sql stable security definer set search_path = public as $$
  with c as (
    select c.* from certificates c
    where (p_code is not null and (upper(c.credential_code) = upper(btrim(p_code)) or c.id::text = lower(btrim(p_code))))
       or (p_code is null and p_uid is not null and p_course is not null and c.uid = p_uid
           and (c.course_key = p_course or c.course_id::text = p_course
                or _course_ident(c.course_name) = _course_ident(replace(p_course, '-', ' '))
                or _course_ident(c.course_name) = _course_ident(regexp_replace(replace(p_course, '-', ' '), '^core ', ''))))
    order by coalesce(c.revoked,false), c.issued_at desc limit 1)
  select case when not exists (select 1 from c) then jsonb_build_object('found', false)
    else (select jsonb_build_object('found', true, 'code', c.credential_code, 'id', c.id,
            'name', coalesce(nullif(c.student_name,''), (select coalesce(nullif(u.name,''), u.display_name) from users u where u.uid = c.uid)),
            'course', coalesce(nullif(c.course_name,''), replace(c.title, 'WODDI Certificate - ', '')),
            'cohort', coalesce(c.cohort, public.cohort_for(c.uid, c.issued_at)),
            'issued_at', c.issued_at, 'revoked', coalesce(c.revoked,false), 'revoke_reason', case when c.revoked then c.revoke_reason end,
            'replaced_by', (select r.credential_code from certificates r where r.id = c.replaced_by)) from c) end;
$$;
grant execute on function public.verify_credential(text, text, text) to anon, authenticated;
